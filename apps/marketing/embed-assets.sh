#!/usr/bin/env bash
# Embeds the NestFlow cover photo and logo into index.html as data: URIs.
#
# Why data: URIs — the published Artifact runs under a strict CSP that blocks
# every external host except Google Fonts, so the page has to carry its own
# images. Embedding also keeps index.html openable straight off disk.
#
# Usage:
#   1. Save the two images into ./assets/ as:
#        assets/cover.jpg   (or .jpeg / .png / .webp)  — the wide banner
#        assets/logo.png                               — the logo, transparent
#   2. bash embed-assets.sh
#
# Re-running is safe: it replaces whatever was embedded last time.
# Passing --logo-only or --cover-only does just that half.

set -euo pipefail
cd "$(dirname "$0")"

HTML="index.html"
[ -f "$HTML" ] || { echo "index.html not found"; exit 1; }

WANT="${1:---both}"

COVER=""
for f in assets/cover.jpg assets/cover.jpeg assets/cover.png assets/cover.webp; do
  [ -f "$f" ] && COVER="$f" && break
done

mime() {
  case "${1##*.}" in
    jpg|jpeg) echo "image/jpeg" ;;
    png)      echo "image/png" ;;
    webp)     echo "image/webp" ;;
    *)        echo "application/octet-stream" ;;
  esac
}

COVER_URI=""
LOGO_URI=""

if [ "$WANT" != "--logo-only" ]; then
  [ -n "$COVER" ] || { echo "No assets/cover.{jpg,jpeg,png,webp} found"; exit 1; }
  echo "Cover : $COVER ($(( $(wc -c < "$COVER") / 1024 )) KB)"
  COVER_URI="data:$(mime "$COVER");base64,$(base64 -w0 "$COVER")"
fi

if [ "$WANT" != "--cover-only" ]; then
  [ -f assets/logo.png ] || { echo "No assets/logo.png found"; exit 1; }
  echo "Logo  : assets/logo.png ($(( $(wc -c < assets/logo.png) / 1024 )) KB)"
  LOGO_URI="data:image/png;base64,$(base64 -w0 assets/logo.png)"
fi

python - "$HTML" "$COVER_URI" "$LOGO_URI" <<'PY'
import io, re, sys

path, cover, logo = sys.argv[1], sys.argv[2], sys.argv[3]
html = io.open(path, encoding="utf-8").read()

# --- 1. the generated custom-property block ---------------------------------
marker = re.compile(r"/\* NF-ASSETS-START.*?/\* NF-ASSETS-END \*/", re.S)
if not marker.search(html):
    raise SystemExit("Marker block not found in index.html - nothing replaced.")

current = marker.search(html).group(0)
keep_cover = cover or (re.search(r"--cover:\s*(.+?);", current, re.S).group(1)
                       if re.search(r"--cover:\s*(.+?);", current, re.S) else "none")
keep_logo = logo or "none"
if not cover:
    m = re.search(r"--cover:\s*(.*?);\n", current, re.S)
    keep_cover = m.group(1) if m else "none"
else:
    keep_cover = 'url("%s")' % cover
if logo:
    keep_logo = 'url("%s")' % logo
else:
    m = re.search(r"--logo:\s*(.*?);\n", current, re.S)
    keep_logo = m.group(1) if m else "none"

block = (
    "/* NF-ASSETS-START - generated by embed-assets.sh, do not edit by hand */\n"
    ":root{\n"
    "  --cover:%s;\n"
    "  --logo:%s;\n"
    "}\n"
    "/* NF-ASSETS-END */"
) % (keep_cover, keep_logo)
html = marker.sub(lambda _: block, html, count=1)

# --- 2. hero: swap the drawn skyline for the photo --------------------------
if cover:
    html = html.replace('<div class="scene" aria-hidden="true">',
                        '<div class="scene has-cover" aria-hidden="true">')

# --- 3. logo: swap every vector mark for the supplied PNG -------------------
if logo:
    img = ('<image href="%s" x="0" y="0" width="120" height="120" '
           'preserveAspectRatio="xMidYMid meet"/>' % logo)
    n = html.count('<use href="#nf-mark"/>')
    html = html.replace('<use href="#nf-mark"/>', img)
    print("  logo swapped into %d places" % n)

io.open(path, "w", encoding="utf-8").write(html)
print("Embedded into %s" % path)
PY

echo "Done. Republish the artifact to push it live."
